// The text of lib/src/dictionary/dictionary_catalog.dart: every pack of a
// directory of built archives, with the size and SHA-256 the app checks its
// download against. Kept out of tool/dictionary_catalog.dart so a test can run
// it on a small directory.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:path/path.dart' as p;

import 'pack_archive.dart';
import 'pack_languages.dart';

/// Where a prerelease's assets are downloaded from.
const String releaseDownloadBase =
    'https://github.com/Nihmar/Niman/releases/download';

/// The catalog's source for the packs archived in [dir] (every `niman-*.tar`),
/// published on the release [tag] (`dictionary-pack-1`).
Future<String> generateCatalog(Directory dir, String tag) async {
  if (!RegExp(r'^dictionary-pack-\d+$').hasMatch(tag)) {
    throw FormatException('"$tag" is not a dictionary-pack-N tag.');
  }
  final pattern = RegExp(r'niman-[a-z]+\.tar$');
  final archives = [
    for (final entity in dir.listSync())
      if (entity is File && pattern.hasMatch(entity.path)) entity,
  ]..sort((a, b) => _rank(a).compareTo(_rank(b)));
  if (archives.isEmpty) {
    throw FormatException('No pack archive in ${dir.path}.');
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/dictionary_catalog.dart; do not edit.')
    ..writeln('// $tag')
    ..writeln()
    ..writeln(
      "import 'package:niman/src/dictionary/dictionary_pack_info.dart';",
    )
    ..writeln()
    ..writeln('/// The release tag the packs are published on.')
    ..writeln("const String dictionaryPackTag = '$tag';")
    ..writeln()
    ..writeln('/// Every dictionary pack, in the order of the settings.')
    ..writeln('const List<DictionaryPackInfo> dictionaryPacks = [');
  for (final archive in archives) {
    final ifo = _readIfo(archive);
    final name = p.basename(archive.path);
    final id = name.substring(0, name.length - '.tar'.length);
    if (ifo['niman-pack'] != '1') {
      throw FormatException('$name is not a version 1 pack.');
    }
    final digest = await sha256.bind(archive.openRead()).first;
    final languages = (ifo['languages'] ?? '').split(',');
    out
      ..writeln('  DictionaryPackInfo(')
      ..writeln('    ${_quote(id)},')
      ..writeln('    languages: [${languages.map(_quote).join(', ')}],')
      ..write(_field('definitions', _quote(ifo['definitions'] ?? '')))
      ..write(_field('source', _quote(ifo['source'] ?? '')))
      ..writeln('    headwords: ${ifo['wordcount']},')
      ..write(_field('fileName', _quote(name)))
      ..write(_field('url', _quote('$releaseDownloadBase/$tag/$name')))
      ..writeln('    bytes: ${archive.lengthSync()},')
      ..write(_field('sha256', _quote(digest.toString())))
      ..writeln('  ),');
  }
  out.writeln('];');
  return out.toString();
}

/// Where a pack sits in the settings: the record's order of languages.
int _rank(File archive) {
  final code = p.basename(archive.path).split('-').last.split('.').first;
  final at = packLanguages.indexWhere((l) => l.code == code);
  return at < 0 ? packLanguages.length : at;
}

/// A `name: value,` line of the constructor call, wrapped as the formatter
/// wraps it: onto its own line when that makes it fit, and left alone when
/// the value is too long for a line anyway (a URL).
String _field(String name, String value) {
  final line = '    $name: $value,';
  final wrapped = '        $value,';
  return line.length <= 80 || wrapped.length > 80
      ? '$line\n'
      : '    $name:\n$wrapped\n';
}

String _quote(String s) {
  final escaped = s
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$');
  return "'$escaped'";
}

/// The `.ifo` inside [archive], as `key: value`.
Map<String, String> _readIfo(File archive) {
  final members = readTarMembers(archive);
  final ifo = members.where((m) => m.name.endsWith('.ifo')).firstOrNull;
  if (ifo == null) throw FormatException('${archive.path} has no .ifo.');
  final text = utf8.decode(readTarMember(archive, ifo));
  return {
    for (final line in text.split('\n').skip(1))
      if (line.contains('='))
        line.substring(0, line.indexOf('=')): line.substring(
          line.indexOf('=') + 1,
        ),
  };
}
