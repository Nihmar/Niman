import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:path/path.dart' as p;

import '../../../tool/dictionary_pack/catalog_writer.dart';
import '../../../tool/dictionary_pack/pack_archive.dart';

/// A pack of hand-written files, archived: its bytes do not depend on a
/// compressor, so the digest in the golden below is a constant.
void _archive(Directory dir, String id, String ifo) {
  final folder = Directory(p.join(dir.path, id))..createSync();
  File(p.join(folder.path, '$id.ifo')).writeAsStringSync(ifo);
  File(p.join(folder.path, '$id.idx')).writeAsStringSync('idx');
  File(p.join(folder.path, '$id.syn')).writeAsStringSync('syn');
  File(p.join(folder.path, '$id.dict.dz')).writeAsStringSync('dz');
  writePackTar(folder, id, File(p.join(dir.path, '$id.tar')));
}

String _ifo(String languages, String definitions, String source, int words) =>
    "StarDict's dict ifo file\n"
    'version=3.0.0\n'
    'bookname=x\n'
    'wordcount=$words\n'
    'synwordcount=0\n'
    'idxfilesize=3\n'
    'idxoffsetbits=32\n'
    'sametypesequence=h\n'
    'niman-pack=1\n'
    'languages=$languages\n'
    'definitions=$definitions\n'
    'source=$source\n';

void main() {
  late Directory dir;

  setUp(() {
    dir = Directory.systemTemp.createTempSync('niman_catalog_test');
    // Written in the order that must not matter: the catalog follows the
    // record's table, not the directory's.
    _archive(dir, 'niman-sh', _ifo('hr,sr,bs', 'en', 'en.wiktionary', 92304));
    _archive(
      dir,
      'niman-it',
      _ifo('it', 'it', 'it.wiktionary+en.wiktionary', 612345),
    );
  });

  tearDown(() => dir.deleteSync(recursive: true));

  Future<String> sha(String id) async =>
      (await sha256.bind(File(p.join(dir.path, '$id.tar')).openRead()).first)
          .toString();

  test('lists every archive with its URL, size and digest', () async {
    final source = await generateCatalog(dir, 'dictionary-pack-1');
    final itBytes = File(p.join(dir.path, 'niman-it.tar')).lengthSync();
    final shBytes = File(p.join(dir.path, 'niman-sh.tar')).lengthSync();
    final itSha = await sha('niman-it');
    final shSha = await sha('niman-sh');
    expect(
      source,
      '// GENERATED by tool/dictionary_catalog.dart; do not edit.\n'
      '// dictionary-pack-1\n'
      '\n'
      "import 'package:niman/src/dictionary/dictionary_pack_info.dart';\n"
      '\n'
      '/// The release tag the packs are published on.\n'
      "const String dictionaryPackTag = 'dictionary-pack-1';\n"
      '\n'
      '/// Every dictionary pack, in the order of the settings.\n'
      'const List<DictionaryPackInfo> dictionaryPacks = [\n'
      '  DictionaryPackInfo(\n'
      "    'niman-it',\n"
      "    languages: ['it'],\n"
      "    definitions: 'it',\n"
      "    source: 'it.wiktionary+en.wiktionary',\n"
      '    headwords: 612345,\n'
      "    fileName: 'niman-it.tar',\n"
      "    url: 'https://github.com/Nihmar/Niman/releases/download/dictionary-pack-1/niman-it.tar',\n"
      '    bytes: $itBytes,\n'
      "    sha256: '$itSha',\n"
      '  ),\n'
      '  DictionaryPackInfo(\n'
      "    'niman-sh',\n"
      "    languages: ['hr', 'sr', 'bs'],\n"
      "    definitions: 'en',\n"
      "    source: 'en.wiktionary',\n"
      '    headwords: 92304,\n'
      "    fileName: 'niman-sh.tar',\n"
      "    url: 'https://github.com/Nihmar/Niman/releases/download/dictionary-pack-1/niman-sh.tar',\n"
      '    bytes: $shBytes,\n'
      "    sha256: '$shSha',\n"
      '  ),\n'
      '];\n',
    );
    // The archive of hand-written files is the same bytes on every host.
    expect(shBytes, 5120);
    expect(
      shSha,
      '0bf6de5362fbe5e5b5990088fe0ccd29ddf2cb5796d7c5c4afda32969fe14e8d',
    );
    expect(itSha, hasLength(64));
    expect(itSha, isNot(shSha));
  });

  test('the digest is the SHA-256 of the archive file', () async {
    final source = await generateCatalog(dir, 'dictionary-pack-7');
    final digest = sha256.convert(
      File(p.join(dir.path, 'niman-sh.tar')).readAsBytesSync(),
    );
    expect(source, contains(digest.toString()));
    expect(source, contains('dictionary-pack-7/niman-sh.tar'));
  });

  test('the generated file is formatted Dart that passes the lints', () async {
    final source = await generateCatalog(dir, 'dictionary-pack-1');
    // Inside the project, so `package:niman/...` resolves.
    final folder = Directory(p.join('.dart_tool', 'niman_catalog_test'))
      ..createSync(recursive: true);
    final file = File(p.join(folder.path, 'dictionary_catalog.dart'))
      ..writeAsStringSync(source);
    try {
      final ProcessResult format;
      try {
        format = await Process.run('dart', [
          'format',
          '--output=none',
          '--set-exit-if-changed',
          file.path,
        ], runInShell: true);
      } on ProcessException {
        markTestSkipped('no dart on the PATH');
        return;
      }
      expect(format.exitCode, 0, reason: 'dart format would change it');
      final analyze = await Process.run('dart', [
        'analyze',
        '--fatal-infos',
        file.path,
      ], runInShell: true);
      expect(
        analyze.exitCode,
        0,
        reason: utf8.decode(utf8.encode('${analyze.stdout}${analyze.stderr}')),
      );
    } finally {
      folder.deleteSync(recursive: true);
    }
  }, timeout: const Timeout(Duration(minutes: 3)));

  test(
    'refuses a tag that is not a dictionary-pack-N, and an empty folder',
    () {
      expect(
        generateCatalog(dir, 'ocr-engine-3'),
        throwsA(isA<FormatException>()),
      );
      expect(
        generateCatalog(
          Directory.systemTemp.createTempSync('niman_empty'),
          'dictionary-pack-1',
        ),
        throwsA(isA<FormatException>()),
      );
    },
  );
}
