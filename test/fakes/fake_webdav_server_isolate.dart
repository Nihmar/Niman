import 'dart:async';
import 'dart:isolate';
import 'dart:typed_data';

import 'package:crypto/crypto.dart';

import 'fake_webdav_server.dart';

/// [length] bytes that depend on [seed] and nothing else: a body for a
/// transfer test that can be made again, on either side of a socket, without
/// shipping it.
Uint8List generatedBytes(int length, {int seed = 0}) {
  final bytes = Uint8List(length);
  var state = (seed * 7919 + 12345) & 0x7fffffff;
  for (var i = 0; i < length; i++) {
    state = (state * 1103515245 + 12345) & 0x7fffffff;
    bytes[i] = state >> 16;
  }
  return bytes;
}

/// A [FakeWebDavServer] that runs in an isolate of its own, for a test that
/// times the client: a server on the client's isolate shares its time, and
/// the number it reads is both of them at once (#1107).
///
/// The files are made and measured over there ([putGenerated], [length],
/// [sha256Of]); only small answers cross.
final class IsolatedWebDavServer {
  new _(this._isolate, this._commands, this._replies, this._events, this.url);

  /// Starts the server and its isolate; the mount has a `.keep` file, so the
  /// folder exists remotely.
  static Future<IsolatedWebDavServer> start() async {
    final replies = ReceivePort();
    final isolate = await Isolate.spawn(_serve, replies.sendPort);
    final events = StreamIterator<Object?>(replies);
    await events.moveNext();
    final ready = events.current! as List<Object?>;
    return IsolatedWebDavServer._(
      isolate,
      ready[0]! as SendPort,
      replies,
      events,
      Uri.parse(ready[1]! as String),
    );
  }

  final Isolate _isolate;
  final SendPort _commands;
  final ReceivePort _replies;
  final StreamIterator<Object?> _events;
  Future<void> _turn = Future<void>.value();

  /// The mount's URL.
  final Uri url;

  /// Replaces the file at [path] with [length] generated bytes.
  Future<void> putGenerated(String path, int length, {int seed = 0}) =>
      _ask(['put', path, length, seed]);

  /// The size of the file at [path], or null when there is none.
  Future<int?> length(String path) async =>
      await _ask(['length', path]) as int?;

  /// The sha256 of the file at [path], or null when there is none.
  Future<String?> sha256Of(String path) async =>
      await _ask(['sha', path]) as String?;

  /// How many files sit under [folder].
  Future<int> filesUnder(String folder) async =>
      (await _ask(['count', folder]))! as int;

  /// Removes every file and folder but the mount's `.keep`.
  Future<void> clear() => _ask(['clear']);

  /// Makes every transfer wait [hold] before it is served; null stops.
  Future<void> hold(Duration? hold) => _ask(['hold', hold?.inMicroseconds]);

  /// Stops the server and its isolate.
  Future<void> close() async {
    await _ask(['close']);
    await _events.cancel();
    _replies.close();
    _isolate.kill(priority: Isolate.immediate);
  }

  /// One command, its answer; commands go one at a time.
  Future<Object?> _ask(List<Object?> command) {
    final turn = _turn.then((_) async {
      _commands.send(command);
      await _events.moveNext();
      return _events.current;
    });
    _turn = turn.then<void>((_) {}, onError: (Object _) {});
    return turn;
  }
}

Future<void> _serve(SendPort out) async {
  final server = await FakeWebDavServer.start()
    ..putFile('.keep', const []);
  final commands = ReceivePort();
  out.send([commands.sendPort, server.url.toString()]);
  await for (final message in commands) {
    final command = message as List<Object?>;
    switch (command[0]) {
      case 'put':
        server.putFile(
          command[1]! as String,
          generatedBytes(command[2]! as int, seed: command[3]! as int),
        );
        out.send(null);
      case 'length':
        out.send(server.file(command[1]! as String)?.length);
      case 'sha':
        final bytes = server.file(command[1]! as String);
        out.send(bytes == null ? null : sha256.convert(bytes).toString());
      case 'count':
        final prefix = '${command[1]}/';
        out.send(
          server.paths
              .where(
                (path) => path.startsWith(prefix) && !server.isFolder(path),
              )
              .length,
        );
      case 'clear':
        for (final path in server.paths) {
          if (path != '.keep' && server.exists(path)) server.remove(path);
        }
        out.send(null);
      case 'hold':
        final micros = command[1] as int?;
        server.holdTransfers = micros == null
            ? null
            : Duration(microseconds: micros);
        out.send(null);
      case 'close':
        await server.close();
        out.send(null);
        commands.close();
    }
  }
}
